function setCorpLang(lang) {
  const t = CORP_T[lang] || CORP_T.ua;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const k = el.dataset.i18n;
    if (t[k] !== undefined) el.textContent = t[k];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const k = el.dataset.i18nPlaceholder;
    if (t[k] !== undefined) el.placeholder = t[k];
  });
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  localStorage.setItem('corp-lang', lang);
}

document.addEventListener('DOMContentLoaded', () => {
  /* Language */
  const saved = localStorage.getItem('corp-lang') || 'ua';
  setCorpLang(saved);
  document.querySelectorAll('.lang-btn').forEach(b => {
    b.addEventListener('click', () => setCorpLang(b.dataset.lang));
  });

  /* Mobile menu */
  const menuBtn = document.getElementById('menu-btn');
  const mobileMenu = document.getElementById('mobile-menu');
  if (menuBtn && mobileMenu) {
    menuBtn.addEventListener('click', () => mobileMenu.classList.toggle('open'));
    mobileMenu.querySelectorAll('a').forEach(a => a.addEventListener('click', () => mobileMenu.classList.remove('open')));
  }

  /* Fade-in */
  const io = new IntersectionObserver(entries => {
    entries.forEach(e => { if (e.isIntersecting) { e.target.classList.add('visible'); io.unobserve(e.target); } });
  }, { threshold: 0.1 });
  document.querySelectorAll('.fade-in').forEach(el => io.observe(el));

  /* Contact form */
  const form = document.getElementById('corp-contact-form');
  if (form) {
    form.addEventListener('submit', e => {
      e.preventDefault();
      const sent = form.querySelector('.form-sent');
      if (sent) { sent.style.display = 'block'; form.reset(); }
    });
  }
});
